def splice(tex: Path, frags: dict[str, str]) -> list[str]:
    src = tex.read_text()
    touched = []
    for name, body in frags.items():
        begin, end = f"% BEGIN GENERATED {name}", f"% END GENERATED {name}"
        pattern = re.compile(
            re.escape(begin) + r".*?" + re.escape(end), re.S
        )
        if not pattern.search(src):
            continue
        # Callable replacement: LaTeX bodies are full of backslashes, which
        # re.sub would otherwise interpret as escape sequences.
        src = pattern.sub(lambda _m, b=body: f"{begin}\n{b}\n{end}", src)
        touched.append(name)
    tex.write_text(src)
    return touched


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True, help="paper directory")
    args = ap.parse_args()
    out = Path(args.out).resolve()

    m = Macros()
    frags = build(m)
    (out / "numbers.tex").write_text(m.render())

    frag_dir = out / "generated"
    frag_dir.mkdir(exist_ok=True)
    for name, body in frags.items():
        (frag_dir / f"{name}.tex").write_text(body + "\n")

    touched = splice(out / "paper.tex", frags)
    missing = sorted(set(frags) - set(touched))

    print(f"wrote {out/'numbers.tex'}  ({len(m.items)} macros)")
    print(f"wrote {len(frags)} fragments to {frag_dir}")
    print(f"spliced into paper.tex: {', '.join(touched) if touched else '(none)'}")
    if missing:
        print(f"NOT spliced (no markers in paper.tex): {', '.join(missing)}")
    return 0


