def load(name: str) -> dict:
    return json.loads((RESULTS / name).read_text())


def pct(x: float | None, places: int = 1) -> str:
    return "--" if x is None else f"{100 * x:.{places}f}"


def ci(d: dict | None) -> str:
    """point [low, high] as percentages."""
    if not d:
        return "--"
    return f"{pct(d['point'])} [{pct(d['ci_low'])}, {pct(d['ci_high'])}]"


# Smallest p we are willing to print as a number. Holm adjustment of an already
# tiny exact-binomial p underflows to 0.0 in double precision; printing that as
# "0" would assert certainty the test cannot provide.
P_FLOOR = 1e-15


def pval(p: float | None) -> str:
    if p is None:
        return "--"
    if p >= 0.01:
        return f"{p:.2f}"
    if p < P_FLOOR:
        return "\\ensuremath{<\\!10^{-15}}"
    exp = f"{p:.0e}".replace("e-0", "e-").replace("e+0", "e")
    mant, e = exp.split("e")
    return f"\\ensuremath{{{mant}\\times10^{{{e}}}}}"


_ROMAN = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
          "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def macro_name(raw: str) -> str:
    """LaTeX control sequences admit only letters."""
    out = []
    for ch in raw:
        if ch.isdigit():
            out.append(_ROMAN[ch])
        elif ch.isalpha():
            out.append(ch)
        elif ch in "_- ":
            out.append("")
    return "Ear" + "".join(out)


class Macros:
    def __init__(self) -> None:
        self.items: dict[str, str] = {}

    def add(self, name: str, value: str) -> None:
        key = macro_name(name)
        if key in self.items and self.items[key] != value:
            raise ValueError(f"macro {key} redefined: {self.items[key]!r} vs {value!r}")
        self.items[key] = value

    def render(self) -> str:
        lines = [
            "% GENERATED by papers/ear_bench/make_tex_fragments.py -- do not edit.",
            "% Every number the manuscript states in prose is defined here.",
            "",
        ]
        for key in sorted(self.items):
            lines.append(f"\\newcommand{{\\{key}}}{{{self.items[key]}}}")
        return "\n".join(lines) + "\n"


def table(caption: str, label: str, spec: str, header: list[str],
          rows: list[list[str]], note: str = "", size: str = "small",
          colsep: str | None = None) -> str:
    out = [
        "\\begin{table}[t]",
        f"\\caption{{{caption}}}\\label{{{label}}}",
        "\\centering",
        f"\\{size}",
        *( [f"\\setlength{{\\tabcolsep}}{{{colsep}}}"] if colsep else [] ),
        f"\\begin{{tabular}}{{{spec}}}",
        "\\toprule",
        " & ".join(header) + " \\\\",
        "\\midrule",
    ]
    out += [" & ".join(r) + " \\\\" for r in rows]
    out += ["\\bottomrule", "\\end{tabular}"]
    if note:
        out.append("\\\\[3pt]")
        out.append(f"\\begin{{minipage}}{{\\linewidth}}\\footnotesize {note}\\end{{minipage}}")
    out.append("\\end{table}")
    return "\n".join(out)


